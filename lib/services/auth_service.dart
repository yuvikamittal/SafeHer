/// Real authentication service backed by Firebase Auth.
///
/// Drop-in replacement for the previous mock. The public API is identical so
/// no changes are needed in login_screen.dart or request_access_screen.dart.
///
/// ── Setup checklist ────────────────────────────────────────────────────────
/// 1. Create a Firebase project at https://console.firebase.google.com
/// 2. Add Android & iOS apps; download google-services.json /
///    GoogleService-Info.plist into the platform folders.
/// 3. Enable "Email/Password" and (optionally) "Google" sign-in methods
///    in Firebase Console → Authentication → Sign-in method.
/// 4. Add to pubspec.yaml:
///      firebase_core: ^3.6.0
///      firebase_auth: ^5.3.1
///      cloud_firestore: ^5.4.4   ← for submitAccessRequest
///      local_auth: ^2.3.0        ← for biometric unlock
/// 5. In main.dart, initialise Firebase before runApp:
///      await Firebase.initializeApp(
///        options: DefaultFirebaseOptions.currentPlatform,
///      );
///    (DefaultFirebaseOptions is generated by `flutterfire configure`.)
/// 6. Android – add to android/app/src/main/AndroidManifest.xml inside
///    <manifest>:
///      <uses-permission android:name="android.permission.USE_BIOMETRIC"/>
///      <uses-permission android:name="android.permission.USE_FINGERPRINT"/>
///    and set minSdkVersion to 23 in android/app/build.gradle.
/// 7. iOS – add to ios/Runner/Info.plist:
///      <key>NSFaceIDUsageDescription</key>
///      <string>SafeHer uses Face ID for quick, secure access.</string>
/// ───────────────────────────────────────────────────────────────────────────

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:local_auth/local_auth.dart';

class AuthService {
  AuthService._();
  static final AuthService instance = AuthService._();

  final FirebaseAuth _auth = FirebaseAuth.instance;
  final FirebaseFirestore _db = FirebaseFirestore.instance;
  final LocalAuthentication _localAuth = LocalAuthentication();

  // ── Current user ──────────────────────────────────────────────────────────

  /// The currently signed-in Firebase user, or null if signed out.
  User? get currentUser => _auth.currentUser;

  /// Stream of auth-state changes — listen to this to reactively update UI.
  Stream<User?> get authStateChanges => _auth.authStateChanges();

  // ── Email / password ──────────────────────────────────────────────────────

  /// Signs in with [email] and [password].
  ///
  /// Returns the verified email address on success.
  /// Throws [FirebaseAuthException] on failure — catch it in the UI and
  /// map [e.code] to a human-readable message (see _friendlyError below).
  Future<String> signInWithEmail(String email, String password) async {
    final credential = await _auth.signInWithEmailAndPassword(
      email: email.trim(),
      password: password,
    );
    return credential.user!.email!;
  }

  /// Creates a new account with [email] and [password], then writes an initial
  /// user document to Firestore so other parts of the app have a profile to
  /// read from day one.
  Future<String> createAccountWithEmail(String email, String password) async {
    final credential = await _auth.createUserWithEmailAndPassword(
      email: email.trim(),
      password: password,
    );
    final user = credential.user!;

    // Create the Firestore user document (only if it doesn't already exist,
    // e.g. in case of a retry after a partial failure).
    final docRef = _db.collection('users').doc(user.uid);
    final snap = await docRef.get();
    if (!snap.exists) {
      await docRef.set({
        'email': user.email,
        'createdAt': FieldValue.serverTimestamp(),
        'biometricEnabled': false,
      });
    }

    return user.email!;
  }

  /// Sends a password-reset email to [email].
  Future<void> sendPasswordReset(String email) async {
    await _auth.sendPasswordResetEmail(email: email.trim());
  }

  // ── Biometric unlock ──────────────────────────────────────────────────────

  /// Returns true if the device has biometrics set up and the user has
  /// enabled biometric login for this account (stored in Firestore).
  Future<bool> isBiometricAvailable() async {
    final canCheck = await _localAuth.canCheckBiometrics;
    final isSupported = await _localAuth.isDeviceSupported();
    if (!canCheck || !isSupported) return false;

    // Also gate on the per-user preference stored in Firestore.
    final uid = _auth.currentUser?.uid;
    if (uid == null) return false;
    final snap = await _db.collection('users').doc(uid).get();
    return snap.data()?['biometricEnabled'] == true;
  }

  /// Prompts the biometric dialog and, on success, re-authenticates silently
  /// using the cached Firebase credential.
  ///
  /// Returns the account email on success.
  /// Throws [Exception] if biometrics are unavailable, not enrolled, or the
  /// user cancels.
  Future<String> signInWithBiometrics() async {
    final canCheck = await _localAuth.canCheckBiometrics;
    final isSupported = await _localAuth.isDeviceSupported();

    if (!canCheck || !isSupported) {
      throw Exception('Biometric authentication is not available on this device.');
    }

    final enrolled = await _localAuth.getAvailableBiometrics();
    if (enrolled.isEmpty) {
      throw Exception('No biometrics enrolled. Please set up fingerprint or Face ID in device settings.');
    }

    final authenticated = await _localAuth.authenticate(
      localizedReason: 'Verify your identity to open SafeHer',
      options: const AuthenticationOptions(
        biometricOnly: true,
        stickyAuth: true, // keeps the prompt open if the app goes to background
      ),
    );

    if (!authenticated) {
      throw Exception('Biometric authentication failed or was cancelled.');
    }

    // The device confirmed the user's identity. Return the cached Firebase
    // user's email — Firebase session is already active from last login.
    final user = _auth.currentUser;
    if (user == null) {
      throw Exception('No cached session found. Please sign in with email first.');
    }
    return user.email ?? 'unknown';
  }

  /// Enables or disables biometric login for the current user.
  /// Call this from the Settings screen toggle.
  Future<void> setBiometricEnabled({required bool enabled}) async {
    final uid = _auth.currentUser?.uid;
    if (uid == null) return;
    await _db.collection('users').doc(uid).update({'biometricEnabled': enabled});
  }

  // ── Profile ───────────────────────────────────────────────────────────────

  /// Live stream of the signed-in user's profile document (name, phone,
  /// address, dob, bloodGroup, etc.). Emits {} when signed out.
  Stream<Map<String, dynamic>> watchProfile() {
    final uid = _auth.currentUser?.uid;
    if (uid == null) return const Stream<Map<String, dynamic>>.empty();
    return _db
        .collection('users')
        .doc(uid)
        .snapshots()
        .map((snap) => snap.data() ?? <String, dynamic>{});
  }

  /// Writes/merges editable profile fields to `users/{uid}`.
  Future<void> updateProfile(Map<String, dynamic> fields) async {
    final uid = _auth.currentUser?.uid;
    if (uid == null) return;
    await _db.collection('users').doc(uid).set(fields, SetOptions(merge: true));
  }

  // ── Access request ────────────────────────────────────────────────────────

  /// Writes an access request to the `access_requests` Firestore collection.
  ///
  /// An admin (or a Cloud Function) can monitor this collection and approve /
  /// reject requests. A status field is included so the UI can poll for
  /// approval state if needed.
  Future<void> submitAccessRequest({
    required String name,
    required String email,
    required String phone,
    required String emergencyContact,
  }) async {
    await _db.collection('access_requests').add({
      'name': name.trim(),
      'email': email.trim(),
      'phone': phone.trim(),
      'emergencyContact': emergencyContact.trim(),
      'status': 'pending', // 'pending' | 'approved' | 'rejected'
      'submittedAt': FieldValue.serverTimestamp(),
    });
  }

  // ── Sign out ──────────────────────────────────────────────────────────────

  Future<void> signOut() async {
    await _auth.signOut();
  }

  // ── Error helper ──────────────────────────────────────────────────────────

  /// Converts a [FirebaseAuthException] code into a user-friendly string.
  ///
  /// Usage in login_screen.dart:
  ///   } on FirebaseAuthException catch (e) {
  ///     ScaffoldMessenger.of(context).showSnackBar(
  ///       SnackBar(content: Text(AuthService.friendlyError(e))),
  ///     );
  ///   }
  static String friendlyError(FirebaseAuthException e) {
    switch (e.code) {
      case 'user-not-found':
        return 'No account found for that email.';
      case 'wrong-password':
        return 'Incorrect password. Please try again.';
      case 'invalid-credential':
        return 'Email or password is incorrect.';
      case 'user-disabled':
        return 'This account has been disabled. Contact support.';
      case 'too-many-requests':
        return 'Too many failed attempts. Try again later or reset your password.';
      case 'email-already-in-use':
        return 'An account with this email already exists.';
      case 'weak-password':
        return 'Password must be at least 6 characters.';
      case 'invalid-email':
        return 'Please enter a valid email address.';
      case 'network-request-failed':
        return 'Network error. Check your connection and try again.';
      default:
        return e.message ?? 'An unexpected error occurred.';
    }
  }
}
